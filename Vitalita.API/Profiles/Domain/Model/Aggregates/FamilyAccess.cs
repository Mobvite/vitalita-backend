using Vitalita.API.Profiles.Domain.Model.Exceptions;
using Vitalita.API.Profiles.Domain.Model.ValueObjects;
using Vitalita.API.Shared.Domain.Model;

namespace Vitalita.API.Profiles.Domain.Model.Aggregates;

/// <summary>
///     Aggregate that gives a family member read-only access to an older adult.
/// </summary>
/// <remarks>
///     <para>
///         It starts as an invitation (<see cref="AccessStatus.Pending" />) before the family member has an account,
///         so <see cref="FamilyMemberId" /> stays <c>null</c> until the invitation is accepted.
///     </para>
///     <list type="bullet">
///         <item><description>Pending → Active: only the invited email, before <see cref="ExpiresAt" />.</description></item>
///         <item><description>Pending or Active → Revoked: the caregiver in charge.</description></item>
///         <item><description>Revoked is final, and an active access never goes back to pending.</description></item>
///     </list>
/// </remarks>
public class FamilyAccess : IAuditableEntity
{
    /// <summary>
    ///     Days an invitation can be accepted.
    /// </summary>
    public const int InvitationValidityDays = 7;

    /// <summary>
    ///     Protected parameterless constructor for EF Core.
    /// </summary>
    protected FamilyAccess()
    {
        InvitedEmail = string.Empty;
        InvitationCode = null!;
    }

    /// <summary>
    ///     Creates a pending invitation that expires in <see cref="InvitationValidityDays" /> days.
    /// </summary>
    /// <param name="olderAdultId">Older adult to share.</param>
    /// <param name="invitedEmail">Email of the invited person; it is stored in lowercase.</param>
    /// <param name="relationship">Relationship with the older adult.</param>
    /// <param name="invitationCode">Code generated by the server.</param>
    /// <param name="utcNow">The current UTC instant.</param>
    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="olderAdultId" /> is not positive.</exception>
    /// <exception cref="ArgumentException">Thrown when <paramref name="invitedEmail" /> is empty.</exception>
    public FamilyAccess(int olderAdultId, string invitedEmail, FamilyRelationship relationship,
        InvitationCode invitationCode, DateTime utcNow) : this()
    {
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(olderAdultId);
        ArgumentException.ThrowIfNullOrWhiteSpace(invitedEmail);
        ArgumentNullException.ThrowIfNull(invitationCode);

        var now = DateTime.SpecifyKind(utcNow, DateTimeKind.Utc);
        OlderAdultId = olderAdultId;
        InvitedEmail = TextNormalizer.NormalizeEmail(invitedEmail);
        Relationship = relationship;
        InvitationCode = invitationCode;
        Status = AccessStatus.Pending;
        InvitedAt = now;
        ExpiresAt = now.AddDays(InvitationValidityDays);
    }

    /// <summary>Gets the server-generated identifier.</summary>
    public int Id { get; private set; }

    /// <summary>Gets the older adult shared.</summary>
    public int OlderAdultId { get; private set; }

    /// <summary>Gets the family member profile, or <c>null</c> while the invitation is pending.</summary>
    public int? FamilyMemberId { get; private set; }

    /// <summary>Gets the email of the invited person (lowercase).</summary>
    public string InvitedEmail { get; private set; }

    /// <summary>Gets the code used to accept the invitation.</summary>
    public InvitationCode InvitationCode { get; private set; }

    /// <summary>Gets the relationship with the older adult.</summary>
    public FamilyRelationship Relationship { get; private set; }

    /// <summary>Gets the access status.</summary>
    public AccessStatus Status { get; private set; }

    /// <summary>Gets the UTC instant of the invitation.</summary>
    public DateTime InvitedAt { get; private set; }

    /// <summary>Gets the UTC instant of the acceptance, if any.</summary>
    public DateTime? AcceptedAt { get; private set; }

    /// <summary>Gets the last UTC instant to accept the invitation.</summary>
    public DateTime ExpiresAt { get; private set; }

    /// <inheritdoc />
    public DateTime? CreatedAt { get; set; }

    /// <inheritdoc />
    public DateTime? UpdatedAt { get; set; }

    /// <summary>Gets a value indicating whether the family member can read the follow-up.</summary>
    public bool IsActive => Status == AccessStatus.Active;

    /// <summary>
    ///     Checks whether the acceptance deadline already passed.
    /// </summary>
    /// <param name="utcNow">The current UTC instant.</param>
    /// <returns><c>true</c> when <paramref name="utcNow" /> is at or after <see cref="ExpiresAt" />.</returns>
    public bool IsExpired(DateTime utcNow) => utcNow >= ExpiresAt;

    /// <summary>
    ///     Checks whether the invitation can still be accepted.
    /// </summary>
    /// <param name="utcNow">The current UTC instant.</param>
    /// <returns><c>true</c> when it is pending and not expired.</returns>
    public bool CanBeAccepted(DateTime utcNow) => Status == AccessStatus.Pending && !IsExpired(utcNow);

    /// <summary>
    ///     Checks whether an email is the invited one (case-insensitive).
    /// </summary>
    /// <param name="email">The email to compare.</param>
    /// <returns><c>true</c> when it matches <see cref="InvitedEmail" />.</returns>
    public bool IsInvited(string? email) =>
        string.Equals(InvitedEmail, TextNormalizer.NormalizeEmail(email), StringComparison.Ordinal);

    /// <summary>
    ///     Accepts the invitation and links the family member profile.
    /// </summary>
    /// <param name="familyMemberId">Profile of the family member that accepts.</param>
    /// <param name="email">Email of the user that accepts.</param>
    /// <param name="utcNow">The current UTC instant.</param>
    /// <exception cref="InvitationEmailMismatchException">Thrown when <paramref name="email" /> is not the invited one.</exception>
    /// <exception cref="InvitationNotAcceptableException">Thrown when the invitation is not pending or has expired.</exception>
    public void Accept(int familyMemberId, string? email, DateTime utcNow)
    {
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(familyMemberId);
        if (!IsInvited(email)) throw new InvitationEmailMismatchException();
        if (!CanBeAccepted(utcNow)) throw new InvitationNotAcceptableException();

        FamilyMemberId = familyMemberId;
        Status = AccessStatus.Active;
        AcceptedAt = DateTime.SpecifyKind(utcNow, DateTimeKind.Utc);
    }

    /// <summary>
    ///     Removes the access. Revoking an access that is already revoked has no effect.
    /// </summary>
    public void Revoke() => Status = AccessStatus.Revoked;

    /// <summary>
    ///     Changes the relationship with the older adult.
    /// </summary>
    /// <param name="relationship">The new relationship.</param>
    /// <exception cref="InvalidAccessStatusTransitionException">Thrown when the access is revoked.</exception>
    public void ChangeRelationship(FamilyRelationship relationship)
    {
        if (relationship == Relationship) return;
        if (Status == AccessStatus.Revoked) throw new InvalidAccessStatusTransitionException();
        Relationship = relationship;
    }
}
